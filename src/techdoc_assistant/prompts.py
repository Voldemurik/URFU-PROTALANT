"""Промпты (инструкции для модели).

Все промпты вынесены в один модуль, чтобы их можно было версионировать и
сравнивать в экспериментах: изменение формулировки — это тоже эксперимент,
который должен отражаться в метриках (см. ``docs/evaluation.md``).
"""

from __future__ import annotations

import re

from techdoc_assistant.documents import Chunk

NO_ANSWER_MARKER = "В предоставленной документации нет информации для ответа на этот вопрос."

# Модели не всегда воспроизводят фразу-отказ дословно; считаем отказом и короткий
# ответ без ссылок, где есть отрицание + «информация/сведения/данные» + упоминание
# документации/контекста («в документации нет сведений о…», «данные … отсутствуют»).
_NEGATION_RE = re.compile(r"\b(нет|отсутству\w*|не содерж\w*|не привед\w*|не указан\w*|не найден\w*)\b", re.I)
_NOUN_RE = re.compile(r"(информаци\w*|сведени\w*|данн\w+)", re.I)
_SOURCE_RE = re.compile(r"(документ\w*|контекст\w*|материал\w*|источник\w*|фрагмент\w*)", re.I)
_CITATION_RE = re.compile(r"\[\d{1,3}\]")


def is_refusal(text: str) -> bool:
    """Отказ: точная фраза-маркер либо короткий ответ «в документации нет сведений» без ссылок."""
    stripped = (text or "").strip()
    if not stripped:
        return True
    if NO_ANSWER_MARKER.rstrip(".").lower() in stripped.lower():
        return True
    if len(stripped) > 200 or _CITATION_RE.search(stripped):
        return False
    return bool(_NEGATION_RE.search(stripped) and _NOUN_RE.search(stripped) and _SOURCE_RE.search(stripped))


SYSTEM_PROMPT = f"""Ты — ассистент инженера по технической документации предприятия.
Отвечай только на основании фрагментов документации, приведённых в разделе «Контекст».

Правила:
1. Используй только сведения из контекста. Не привлекай внешние знания и не додумывай.
2. После каждого утверждения ставь ссылку на фрагмент-источник в квадратных скобках, например [1] или [2][3].
3. Если в контексте нет нужных сведений, ответь ровно одной фразой: «{NO_ANSWER_MARKER}»
4. Сохраняй точные значения, единицы измерения, коды ошибок и номера пунктов так, как они записаны в документе.
5. Отвечай на русском языке, кратко и по делу. Если уместно, используй нумерованный список шагов.
"""

USER_TEMPLATE = """Контекст:
{context}

Вопрос: {question}

Ответ:"""


def format_context(chunks: list[Chunk]) -> str:
    blocks = []
    for number, chunk in enumerate(chunks, start=1):
        blocks.append(f"[{number}] Источник: {chunk.label()} (файл: {chunk.doc_id})\n{chunk.text}")
    return "\n\n".join(blocks)


def build_user_prompt(question: str, chunks: list[Chunk]) -> str:
    return USER_TEMPLATE.format(context=format_context(chunks), question=question.strip())


